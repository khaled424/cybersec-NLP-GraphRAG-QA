"""In-memory property graph with a small read-only Cypher subset.

The notebooks, tests and MVP must run without a Neo4j server. This backend accepts the
single-hop patterns typically generated by Text-to-Cypher models::

    MATCH (a:Actor {name: 'APT29'})-[r:USES]->(m:Malware) WHERE m.family = 'loader'
    RETURN DISTINCT m.name AS malware, r.source LIMIT 5

and raises :class:`CypherError` with an actionable message (unknown label, relationship
type or property) like Neo4j would, so an agent can learn from failures. Write clauses
are rejected: the retrieval path of a RAG system must be read-only.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any

_WRITE_KEYWORDS = re.compile(
    r"\b(CREATE|MERGE|DELETE|DETACH|SET|REMOVE|DROP|CALL|LOAD\s+CSV|FOREACH)\b", re.IGNORECASE
)


def _node(v: str) -> str:
    return (
        rf"\(\s*(?P<{v}>\w+)(?::(?P<{v}_label>\w+))?"
        rf"(?:\s*\{{\s*(?P<{v}_prop>\w+)\s*:\s*(?P<{v}_q>['\"])(?P<{v}_val>.*?)(?P={v}_q)\s*\}})?\s*\)"
    )


_PATTERN = re.compile(
    r"^\s*MATCH\s*" + _node("a")
    + r"\s*(?P<left><)?-\s*\[\s*(?P<relvar>\w+)?\s*:\s*(?P<rel>\w+)\s*\]\s*-(?P<right>>)?\s*"
    + _node("b")
    + r"(?:\s+WHERE\s+(?P<where>.+?))?"
    + r"\s+RETURN\s+(?P<distinct>DISTINCT\s+)?(?P<ret>.+?)(?:\s+LIMIT\s+(?P<limit>\d+))?\s*;?\s*$",
    re.IGNORECASE | re.DOTALL,
)
_CONDITION = re.compile(r"^\s*(\w+)\.(\w+)\s*=\s*(['\"])(.*?)\3\s*$", re.DOTALL)
_RETURN_ITEM = re.compile(r"^\s*(\w+)(?:\.(\w+))?(?:\s+AS\s+(\w+))?\s*$", re.IGNORECASE)


class CypherError(Exception):
    """Raised when a query is invalid for the graph schema (mirrors a Neo4j error)."""


@dataclass
class Node:
    id: str
    label: str
    name: str
    props: dict[str, Any] = field(default_factory=dict)


@dataclass
class Edge:
    src: str
    rel: str
    dst: str
    props: dict[str, Any] = field(default_factory=dict)


@dataclass
class Schema:
    labels: list[str]
    relationships: list[str]
    properties: list[str]

    def describe(self) -> str:
        return (
            f"Labels: {', '.join(self.labels)}\n"
            f"Relationships: {', '.join(self.relationships)}\n"
            f"Properties: {', '.join(self.properties)}"
        )


class InMemoryGraph:
    """Minimal labelled property graph (nodes, typed directed edges, properties)."""

    def __init__(self) -> None:
        self.nodes: dict[str, Node] = {}
        self.edges: list[Edge] = []

    def add_node(self, label: str, name: str, **props: Any) -> str:
        node_id = f"{label}:{name}"
        self.nodes[node_id] = Node(node_id, label, name, dict(props))
        return node_id

    def add_edge(self, src: str, rel: str, dst: str, **props: Any) -> None:
        if src not in self.nodes or dst not in self.nodes:
            raise KeyError(f"unknown endpoint for edge {src} -[{rel}]-> {dst}")
        self.edges.append(Edge(src, rel, dst, dict(props)))

    def copy(self) -> InMemoryGraph:
        clone = InMemoryGraph()
        clone.nodes = {k: Node(n.id, n.label, n.name, dict(n.props)) for k, n in self.nodes.items()}
        clone.edges = [Edge(e.src, e.rel, e.dst, dict(e.props)) for e in self.edges]
        return clone

    def to_dict(self) -> dict[str, list[dict[str, Any]]]:
        """JSON-serialisable form (``knowledge_graph.json`` exchange format)."""
        return {
            "nodes": [{"label": n.label, "name": n.name, "props": n.props} for n in self.nodes.values()],
            "edges": [{"src": e.src, "rel": e.rel, "dst": e.dst, "props": e.props} for e in self.edges],
        }

    @classmethod
    def from_dict(cls, data: dict[str, list[dict[str, Any]]]) -> InMemoryGraph:
        graph = cls()
        for node in data["nodes"]:
            graph.add_node(node["label"], node["name"], **node.get("props", {}))
        for edge in data["edges"]:
            props = dict(edge.get("props", {}))
            if "source" in edge:  # legacy flat format
                props.setdefault("source", edge["source"])
            graph.add_edge(edge["src"], edge["rel"], edge["dst"], **props)
        return graph

    def node_id(self, label: str, name: str) -> str:
        return f"{label}:{name}"

    def schema(self) -> Schema:
        props = {"name"}
        for node in self.nodes.values():
            props.update(node.props)
        return Schema(
            labels=sorted({n.label for n in self.nodes.values()}),
            relationships=sorted({e.rel for e in self.edges}),
            properties=sorted(props),
        )

    def run(self, query: str) -> list[dict[str, Any]]:
        """Execute a read-only single-hop query and return one dict per row.

        Supported: ``MATCH (a:L {prop: 'v'})-[r:REL]->(b:L) [WHERE x.p = 'v' AND ...]
        RETURN [DISTINCT] x.p [AS alias], ... [LIMIT n]`` (arrow in either direction).
        """
        if _WRITE_KEYWORDS.search(query):
            raise CypherError("Write or procedure clauses are not allowed (read-only graph access).")
        match = _PATTERN.match(query)
        if not match:
            raise CypherError(
                "Syntax error: expected MATCH (a:Label {name: '...'})-[:REL]->(b:Label) "
                "[WHERE a.prop = '...'] RETURN b.name [LIMIT n] (single hop, no ORDER BY / variable length)."
            )
        if re.search(r"\bORDER\s+BY\b", match.group("ret"), re.IGNORECASE):
            raise CypherError("Syntax error: ORDER BY is not supported by this backend.")
        schema = self.schema()
        for key in ("a_label", "b_label"):
            label = match.group(key)
            if label and label not in schema.labels:
                raise CypherError(f"Unknown label `{label}`. Known labels: {schema.labels}")
        rel = match.group("rel")
        if rel not in schema.relationships:
            raise CypherError(f"Unknown relationship type `{rel}`. Known types: {schema.relationships}")

        a, b, relvar = match.group("a"), match.group("b"), match.group("relvar")
        filters: dict[str, list[tuple[str, str]]] = {a: [], b: []}
        for var in ("a", "b"):
            if match.group(f"{var}_prop"):
                filters[match.group(var)].append((match.group(f"{var}_prop"), match.group(f"{var}_val")))
        if match.group("where"):
            for condition in re.split(r"\s+AND\s+", match.group("where"), flags=re.IGNORECASE):
                parsed = _CONDITION.match(condition)
                if not parsed or parsed.group(1) not in filters:
                    raise CypherError(f"Unsupported WHERE condition `{condition.strip()}` (use var.prop = 'value').")
                filters[parsed.group(1)].append((parsed.group(2), parsed.group(4)))
        for conditions in filters.values():
            for prop, _ in conditions:
                if prop not in schema.properties:
                    raise CypherError(f"Unknown property `{prop}`. Known properties: {schema.properties}")

        columns = []
        for item in match.group("ret").split(","):
            parsed = _RETURN_ITEM.match(item)
            if not parsed:
                raise CypherError(f"Unsupported RETURN expression `{item.strip()}`.")
            var, prop, alias = parsed.groups()
            if var not in (a, b, relvar):
                raise CypherError(f"Variable `{var}` not defined.")
            if var != relvar and prop and prop not in schema.properties:
                raise CypherError(f"Unknown property `{prop}`. Known properties: {schema.properties}")
            columns.append((var, prop, alias or (f"{var}.{prop}" if prop else var)))

        reverse = bool(match.group("left")) and not match.group("right")
        rows: list[dict[str, Any]] = []
        seen: set[tuple] = set()
        for edge in self.edges:
            if edge.rel != rel:
                continue
            left, right = (edge.dst, edge.src) if reverse else (edge.src, edge.dst)
            bound = {a: self.nodes[left], b: self.nodes[right]}
            if not self._ok(bound[a], match.group("a_label"), filters[a]):
                continue
            if not self._ok(bound[b], match.group("b_label"), filters[b]):
                continue
            row: dict[str, Any] = {}
            for var, prop, alias in columns:
                if var == relvar:
                    row[alias] = edge.props.get(prop) if prop else edge.rel
                else:
                    node = bound[var]
                    row[alias] = node.name if prop in (None, "name") else node.props.get(prop)
            if match.group("distinct"):
                key = tuple(row.values())
                if key in seen:
                    continue
                seen.add(key)
            row["_edge"] = edge
            rows.append(row)
        limit = match.group("limit")
        return rows[: int(limit)] if limit else rows

    @staticmethod
    def _ok(node: Node, label: str | None, conditions: list[tuple[str, str]]) -> bool:
        if label is not None and node.label != label:
            return False
        return all((node.name if prop == "name" else str(node.props.get(prop))) == value for prop, value in conditions)
